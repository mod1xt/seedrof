(function(){
  try {
    var saved = localStorage.getItem('alfa_lang') || 'en';
    if(!window.ALFA_LANG || !window.ALFA_LANG[saved]) saved = 'en';
    window._currentLang = saved;
    function _restoreLang(){
      if(typeof window.applyLang === 'function') window.applyLang(saved);
      var sel = document.getElementById('langSelect');
      if(sel) sel.value = saved;
    }
    if(document.readyState !== 'loading') {
      setTimeout(_restoreLang, 150);
    } else {
      document.addEventListener('DOMContentLoaded', function(){ setTimeout(_restoreLang, 150); });
    }
  } catch(e){}
})();

window.changeLang = function(code) {
  if (code === window._currentLang) return;

  
  var ov = document.getElementById('_langLoadOverlay');
  if (!ov) {
    ov = document.createElement('div');
    ov.id = '_langLoadOverlay';
    ov.style.cssText = 'position:fixed;inset:0;z-index:69999;background:rgba(6,5,14,.96);backdrop-filter:blur(16px);display:flex;flex-direction:column;align-items:center;justify-content:center;gap:18px;opacity:0;transition:opacity .22s ease;';
    ov.innerHTML =
      '<div style="width:52px;height:52px;border:4px solid rgba(124,92,255,.2);border-top:4px solid #7c5cff;border-radius:50%;animation:spin 1s linear infinite;"></div>'+
      '<div id="_langLoadTxt" style="font-family:Outfit,sans-serif;font-size:.85rem;font-weight:600;color:rgba(200,195,255,.8);letter-spacing:.04em;">Switching language…</div>';
    document.body.appendChild(ov);
  }
  ov.style.display = 'flex';
  void ov.offsetWidth;
  ov.style.opacity = '1';

  var msgs = { ar:'جارٍ تغيير اللغة…', ru:'Смена языка…', zh:'正在切换语言…', es:'Cambiando idioma…', tr:'Dil değiştiriliyor…', fa:'در حال تغییر زبان…', en:'Switching language…' };
  var loadTxt = document.getElementById('_langLoadTxt');
  if (loadTxt) loadTxt.textContent = msgs[code] || msgs.en;

  setTimeout(function() {
    window.applyLang(code);
    setTimeout(function() {
      ov.style.opacity = '0';
      setTimeout(function(){ ov.style.display='none'; }, 220);
    }, 400);
  }, 600);
};